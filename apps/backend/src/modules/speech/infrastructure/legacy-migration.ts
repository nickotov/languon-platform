import { createHash, createHmac, randomUUID } from 'node:crypto';
import { isDeepStrictEqual } from 'node:util';
import { and, asc, eq, gt, inArray, sql } from 'drizzle-orm';
import type { PostgresJsDatabase } from '@languon/database';
import type { databaseSchema } from '../../../infrastructure/database/schema';
import {
    dictionaryAudioAssetsTable as legacyAssets,
    dictionaryAudioBindingsTable as legacyBindings,
    dictionaryAudioJobsTable as legacyJobs,
} from '../../dictionaries/infrastructure/persistence/drizzle/audio-schema';
import type { AudioObjectStorage } from '../application/ports';
import { assertAudioIntegrity } from '../domain/audio-integrity';
import {
    NORMALIZATION_REVISION,
    normalizeSpeechText,
    speechTextIdentity,
} from '../domain/speech-policy';
import {
    speechBindingsTable as bindings,
    speechJobsTable as jobs,
    speechRecordingsTable as recordings,
} from './schema';
import type {
    DrizzleSpeechSourceResolver,
    SpeechSourceTransaction,
} from './source-resolver';

type LegacyJob = typeof legacyJobs.$inferSelect;
type Recording = typeof recordings.$inferSelect;
export interface LegacySpeechMigrationReport {
    promoted: number;
    reused: number;
    resumed: number;
    blockedUnknown: number;
    skippedSource: number;
    deferredActive: number;
}
export class LegacySpeechMigrationBlockedError extends Error {}

/** Copies already generated bytes only. This module has no synthesis-provider capability. */
export class LegacySpeechMigration {
    public constructor(
        private readonly options: {
            database: PostgresJsDatabase<typeof databaseSchema>;
            resolver: Pick<DrizzleSpeechSourceResolver, 'resolveInTransaction'>;
            storage: AudioObjectStorage;
            fingerprintSecret: string;
            retainedFingerprintSecrets?: readonly string[];
            now?: () => Date;
        },
    ) {}
    public async run(): Promise<LegacySpeechMigrationReport> {
        const report: LegacySpeechMigrationReport = {
            promoted: 0,
            reused: 0,
            resumed: 0,
            blockedUnknown: 0,
            skippedSource: 0,
            deferredActive: 0,
        };
        const pending = await this.options.database
            .select({ id: legacyJobs.id })
            .from(legacyJobs)
            .where(
                inArray(legacyJobs.state, [
                    'queued',
                    'submitting',
                    'waiting_provider',
                    'storing',
                ]),
            )
            .limit(1);
        if (pending.length)
            throw new LegacySpeechMigrationBlockedError(
                'Drain known legacy tasks and cancel queued legacy work before migration.',
            );
        const unknown = await this.options.database
            .select()
            .from(legacyJobs)
            .where(eq(legacyJobs.state, 'submission_unknown'));
        // Resolve every uncertain task before modifying anything. Unresolved tasks require operator reconciliation.
        const uncertain = new Map<string, LegacyJob>();
        for (const job of unknown)
            await this.options.database.transaction(async (tx) => {
                const identity = await this.resolve(job, tx);
                const [ready] = await tx
                    .select({ id: recordings.id })
                    .from(recordings)
                    .where(
                        and(
                            inArray(recordings.canonicalKey, identity.keys),
                            eq(recordings.state, 'ready'),
                        ),
                    )
                    .limit(1);
                if (ready)
                    throw new LegacySpeechMigrationBlockedError(
                        'An uncertain legacy task collides with a ready shared recording; reconcile before cutover.',
                    );
                for (const key of identity.keys) {
                    const previous = uncertain.get(key);
                    if (
                        previous &&
                        (!job.taskId ||
                            previous.taskId !== job.taskId ||
                            !isDeepStrictEqual(previous.profile, job.profile))
                    )
                        throw new LegacySpeechMigrationBlockedError(
                            'Distinct uncertain legacy provider tasks map to one canonical recording; reconcile before cutover.',
                        );
                    uncertain.set(key, job);
                }
            });
        for (const job of unknown) {
            await this.blockUnknown(job);
            report.blockedUnknown++;
        }
        let cursor: string | undefined;
        while (true) {
            const rows = await this.options.database
                .select({ asset: legacyAssets, job: legacyJobs })
                .from(legacyAssets)
                .innerJoin(legacyJobs, eq(legacyJobs.assetId, legacyAssets.id))
                .innerJoin(
                    legacyBindings,
                    and(
                        eq(legacyBindings.jobId, legacyJobs.id),
                        eq(legacyBindings.ownerId, legacyAssets.ownerId),
                        eq(legacyBindings.cardId, legacyAssets.cardId),
                        eq(legacyBindings.field, legacyAssets.field),
                    ),
                )
                .where(
                    and(
                        eq(legacyAssets.state, 'ready'),
                        eq(legacyJobs.state, 'ready'),
                        cursor ? gt(legacyAssets.id, cursor) : undefined,
                    ),
                )
                .orderBy(asc(legacyAssets.id))
                .limit(100);
            if (!rows.length) break;
            for (const row of rows) {
                const outcome = await this.promote(row.asset, row.job);
                report[outcome]++;
            }
            cursor = rows.at(-1)!.asset.id;
        }
        return report;
    }
    private source(job: LegacyJob) {
        if (
            ![
                'source',
                'translation',
                'example',
                'exampleTranslation',
            ].includes(job.field)
        )
            throw new LegacySpeechMigrationBlockedError(
                'Unknown legacy field.',
            );
        return {
            kind: 'dictionary-field' as const,
            access: { kind: 'owner' as const, dictionaryId: job.dictionaryId },
            cardId: job.cardId,
            field: job.field as
                'source' | 'translation' | 'example' | 'exampleTranslation',
        };
    }
    private async resolve(job: LegacyJob, tx: SpeechSourceTransaction) {
        const source = this.source(job);
        let resolved: Awaited<
            ReturnType<DrizzleSpeechSourceResolver['resolveInTransaction']>
        >;
        try {
            resolved = await this.options.resolver.resolveInTransaction(
                job.ownerId,
                source,
                tx,
            );
        } catch {
            throw new LegacySpeechMigrationBlockedError(
                'A legacy source is unavailable; reconcile uncertain work before cutover.',
            );
        }
        const legacyText = resolved.text.trim();
        const expected = [
            this.options.fingerprintSecret,
            ...(this.options.retainedFingerprintSecrets ?? []),
        ].map((secret) =>
            createHmac('sha256', secret)
                .update(
                    JSON.stringify([
                        job.ownerId,
                        job.cardId,
                        job.field,
                        legacyText,
                        resolved.language,
                    ]),
                )
                .digest('hex'),
        );
        if (!expected.includes(job.fingerprint))
            throw new LegacySpeechMigrationBlockedError(
                'Legacy HMAC fingerprint mismatch.',
            );
        if (job.text && job.text !== legacyText)
            throw new LegacySpeechMigrationBlockedError(
                'Legacy text no longer matches the authorized source.',
            );
        if (job.profile.language !== resolved.language)
            throw new LegacySpeechMigrationBlockedError(
                'Legacy language no longer matches the authorized source.',
            );
        const text = normalizeSpeechText(resolved.text);
        const key = speechTextIdentity(
            this.options.fingerprintSecret,
            resolved.language,
            text,
        );
        const keys = [
            this.options.fingerprintSecret,
            ...(this.options.retainedFingerprintSecrets ?? []),
        ].map((secret) => speechTextIdentity(secret, resolved.language, text));
        return { source, resolved, text, key, keys };
    }
    private async lock(tx: SpeechSourceTransaction, key: string) {
        await tx.execute(
            sql`select set_config('languon.speech_worker_version','1',true),set_config('languon.model_pricing_revision','1',true)`,
        );
        await tx.execute(
            sql`select pg_advisory_xact_lock(hashtextextended(${key},1920424383))`,
        );
    }
    private operation(job: LegacyJob) {
        const hex = createHash('sha256')
            .update(
                JSON.stringify([
                    'legacy-audio-binding-v1',
                    job.assetId,
                    job.ownerId,
                    job.cardId,
                    job.field,
                ]),
            )
            .digest('hex');
        return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-5${hex.slice(13, 16)}-a${hex.slice(17, 20)}-${hex.slice(20, 32)}`;
    }
    private async attach(
        tx: SpeechSourceTransaction,
        job: LegacyJob,
        identity: Awaited<ReturnType<LegacySpeechMigration['resolve']>>,
        recordingId: string,
        jobId: string | null,
    ) {
        const [legacyBinding] = await tx
            .select({ id: legacyBindings.id })
            .from(legacyBindings)
            .where(
                and(
                    eq(legacyBindings.jobId, job.id),
                    eq(legacyBindings.ownerId, job.ownerId),
                    eq(legacyBindings.cardId, job.cardId),
                    eq(legacyBindings.field, job.field),
                ),
            )
            .limit(1);
        await tx
            .insert(bindings)
            .values({
                id: randomUUID(),
                actorId: job.ownerId,
                dictionaryId: identity.resolved.dictionaryId,
                cardId: job.cardId,
                source: identity.source,
                sourceRevision: identity.resolved.revision,
                operationId: legacyBinding?.id ?? this.operation(job),
                recordingId,
                jobId,
                createdAt: this.now(),
            })
            .onConflictDoUpdate({
                target: [bindings.actorId, bindings.operationId],
                set: {
                    source: identity.source,
                    sourceRevision: identity.resolved.revision,
                    recordingId,
                    jobId,
                },
            });
    }
    private async blockUnknown(job: LegacyJob) {
        await this.options.database.transaction(async (tx) => {
            const identity = await this.resolve(job, tx);
            await this.lock(tx, identity.key);
            const [ready] = await tx
                .select()
                .from(recordings)
                .where(
                    and(
                        inArray(recordings.canonicalKey, identity.keys),
                        eq(recordings.state, 'ready'),
                    ),
                )
                .orderBy(asc(recordings.createdAt))
                .limit(1);
            if (ready) {
                throw new LegacySpeechMigrationBlockedError(
                    'An uncertain legacy task collides with a ready shared recording; reconcile before cutover.',
                );
            }
            const [active] = await tx
                .select()
                .from(jobs)
                .where(
                    and(
                        inArray(jobs.canonicalKey, identity.keys),
                        inArray(jobs.state, [
                            'queued',
                            'submitting',
                            'processing',
                            'storing',
                            'submission_unknown',
                        ]),
                    ),
                )
                .limit(1);
            if (active) {
                const [recording] = await tx
                    .select({ profile: recordings.profile })
                    .from(recordings)
                    .where(eq(recordings.id, active.recordingId))
                    .limit(1);
                if (
                    active.state !== 'submission_unknown' ||
                    active.taskId !== job.taskId ||
                    (active.id !== job.id && !job.taskId) ||
                    !isDeepStrictEqual(recording?.profile, job.profile)
                )
                    throw new LegacySpeechMigrationBlockedError(
                        'A shared task conflicts with an uncertain legacy submission; reconcile before cutover.',
                    );
                await this.attach(
                    tx,
                    job,
                    identity,
                    active.recordingId,
                    active.id,
                );
                return;
            }
            const now = this.now();
            await tx
                .insert(recordings)
                .values({
                    id: job.assetId,
                    canonicalKey: identity.key,
                    text: identity.text,
                    language: identity.resolved.language,
                    normalizationRevision: NORMALIZATION_REVISION,
                    profile: job.profile,
                    state: 'pending',
                    storage: {
                        ...this.options.storage.identity,
                        key: `speech/${job.assetId}`,
                    },
                    createdAt: now,
                    lastAccessedAt: now,
                })
                .onConflictDoNothing();
            const [existing] = await tx
                .select()
                .from(recordings)
                .where(eq(recordings.id, job.assetId))
                .limit(1);
            if (
                !existing ||
                !identity.keys.includes(existing.canonicalKey) ||
                existing.state !== 'pending' ||
                !isDeepStrictEqual(existing.profile, job.profile)
            )
                throw new LegacySpeechMigrationBlockedError(
                    'The legacy destination inventory conflicts with existing data.',
                );
            await tx
                .insert(jobs)
                .values({
                    id: job.id,
                    recordingId: job.assetId,
                    canonicalKey: identity.key,
                    payerId: null,
                    credits: 0n,
                    estimatedCostUnits: job.reservedCost,
                    billingState: 'free',
                    state: 'submission_unknown',
                    taskId: job.taskId,
                    nextPollAt: now,
                    createdAt: job.createdAt,
                    billingDeadline: now,
                    recoveryDeadline: now,
                    error: 'legacy_submission_requires_operator_reconciliation',
                })
                .onConflictDoNothing();
            const [blocker] = await tx
                .select()
                .from(jobs)
                .where(eq(jobs.id, job.id))
                .limit(1);
            if (
                !blocker ||
                blocker.state !== 'submission_unknown' ||
                blocker.taskId !== job.taskId ||
                !identity.keys.includes(blocker.canonicalKey) ||
                blocker.recordingId !== job.assetId
            )
                throw new LegacySpeechMigrationBlockedError(
                    'Legacy blocker identity conflicts with existing work.',
                );
            await this.attach(tx, job, identity, job.assetId, job.id);
        });
    }
    private async promote(
        asset: typeof legacyAssets.$inferSelect,
        job: LegacyJob,
    ): Promise<
        'promoted' | 'reused' | 'resumed' | 'skippedSource' | 'deferredActive'
    > {
        if (
            asset.ownerId !== job.ownerId ||
            asset.dictionaryId !== job.dictionaryId ||
            asset.cardId !== job.cardId ||
            asset.field !== job.field ||
            asset.fingerprint !== job.fingerprint
        )
            throw new LegacySpeechMigrationBlockedError(
                'Legacy asset ownership or content identity does not match its generating job.',
            );
        let plan: {
            recording: Recording;
            identity: Awaited<ReturnType<LegacySpeechMigration['resolve']>>;
            reused: boolean;
        } | null;
        try {
            plan = await this.options.database.transaction(async (tx) => {
                const identity = await this.resolve(job, tx);
                await this.lock(tx, identity.key);
                const [ready] = await tx
                    .select()
                    .from(recordings)
                    .where(
                        and(
                            inArray(recordings.canonicalKey, identity.keys),
                            eq(recordings.state, 'ready'),
                        ),
                    )
                    .orderBy(asc(recordings.createdAt))
                    .limit(1);
                if (ready) {
                    await this.attach(tx, job, identity, ready.id, null);
                    return { recording: ready, identity, reused: true };
                }
                const [active] = await tx
                    .select({ id: jobs.id })
                    .from(jobs)
                    .where(
                        and(
                            inArray(jobs.canonicalKey, identity.keys),
                            inArray(jobs.state, [
                                'queued',
                                'submitting',
                                'processing',
                                'storing',
                                'submission_unknown',
                            ]),
                        ),
                    )
                    .limit(1);
                if (active) return null;
                const now = this.now();
                await tx
                    .insert(recordings)
                    .values({
                        id: asset.id,
                        canonicalKey: identity.key,
                        text: identity.text,
                        language: identity.resolved.language,
                        normalizationRevision: NORMALIZATION_REVISION,
                        profile: job.profile,
                        state: 'pending',
                        storage: {
                            ...this.options.storage.identity,
                            key: `speech/${asset.id}`,
                        },
                        createdAt: asset.createdAt,
                        lastAccessedAt: now,
                    })
                    .onConflictDoNothing();
                const [recording] = await tx
                    .select()
                    .from(recordings)
                    .where(eq(recordings.id, asset.id))
                    .limit(1);
                if (
                    !recording ||
                    !identity.keys.includes(recording.canonicalKey) ||
                    recording.state !== 'pending'
                )
                    throw new LegacySpeechMigrationBlockedError(
                        'A migration inventory collision requires reconciliation.',
                    );
                return { recording, identity, reused: false };
            });
        } catch (error) {
            if (error instanceof LegacySpeechMigrationBlockedError)
                return 'skippedSource';
            throw error;
        }
        if (!plan) return 'deferredActive';
        if (plan.reused) {
            const existingAudio = await this.options.storage.read(
                plan.recording.storage,
            );
            if (!existingAudio)
                throw new LegacySpeechMigrationBlockedError(
                    'Reusable recording bytes are unavailable; repair its inventory before retiring legacy audio.',
                );
            assertAudioIntegrity(existingAudio);
            if (
                existingAudio.checksum !== plan.recording.checksum ||
                existingAudio.bytes.byteLength !== plan.recording.byteLength
            )
                throw new LegacySpeechMigrationBlockedError(
                    'Reusable recording integrity does not match its inventory.',
                );
            await this.retire(asset.id);
            return 'reused';
        }
        if (!asset.checksum || !asset.byteLength)
            throw new LegacySpeechMigrationBlockedError(
                'Legacy audio metadata is incomplete.',
            );
        let audio = await this.options.storage.read(plan.recording.storage);
        const resumed = !!audio;
        if (!audio) {
            audio = await this.options.storage.read(asset.storage);
            if (!audio)
                throw new LegacySpeechMigrationBlockedError(
                    'Legacy audio bytes are unavailable.',
                );
        }
        assertAudioIntegrity(audio);
        if (
            audio.checksum !== asset.checksum ||
            audio.bytes.byteLength !== asset.byteLength
        )
            throw new LegacySpeechMigrationBlockedError(
                'Legacy audio checksum or size does not match its inventory.',
            );
        const storage = resumed
            ? plan.recording.storage
            : await this.options.storage.putForReference(
                  plan.recording.storage,
                  audio,
              );
        const published = await this.options.database.transaction(
            async (tx) => {
                let identity: Awaited<
                    ReturnType<LegacySpeechMigration['resolve']>
                >;
                try {
                    identity = await this.resolve(job, tx);
                } catch {
                    return false;
                }
                await this.lock(tx, identity.key);
                if (
                    identity.resolved.revision !==
                    plan.identity.resolved.revision
                )
                    return false;
                const [active] = await tx
                    .select({ id: jobs.id })
                    .from(jobs)
                    .where(
                        and(
                            inArray(jobs.canonicalKey, identity.keys),
                            inArray(jobs.state, [
                                'queued',
                                'submitting',
                                'processing',
                                'storing',
                                'submission_unknown',
                            ]),
                        ),
                    )
                    .limit(1);
                if (active) return false;
                const updated = await tx
                    .update(recordings)
                    .set({
                        state: 'ready',
                        storage,
                        checksum: audio.checksum,
                        byteLength: audio.bytes.byteLength,
                        lastAccessedAt: this.now(),
                        version: plan.recording.version + 1,
                    })
                    .where(
                        and(
                            eq(recordings.id, plan.recording.id),
                            eq(recordings.version, plan.recording.version),
                            eq(recordings.state, 'pending'),
                        ),
                    )
                    .returning({ id: recordings.id });
                if (!updated.length) return false;
                await this.attach(tx, job, identity, plan.recording.id, null);
                return true;
            },
        );
        if (!published) {
            // Leave durable pending inventory for another pass; never erase legacy bytes after a failed publication.
            return 'skippedSource';
        }
        await this.retire(asset.id);
        return resumed ? 'resumed' : 'promoted';
    }
    private async retire(assetId: string) {
        // Legacy purge worker remains responsible for physical deletion and all storage versions.
        await this.options.database.transaction(async (tx) => {
            await tx
                .delete(legacyBindings)
                .where(
                    inArray(
                        legacyBindings.jobId,
                        tx
                            .select({ id: legacyJobs.id })
                            .from(legacyJobs)
                            .where(eq(legacyJobs.assetId, assetId)),
                    ),
                );
            await tx
                .update(legacyAssets)
                .set({ state: 'deleting', writerExpiresAt: null })
                .where(
                    and(
                        eq(legacyAssets.id, assetId),
                        eq(legacyAssets.state, 'ready'),
                    ),
                );
        });
    }
    private now() {
        return this.options.now?.() ?? new Date();
    }
}

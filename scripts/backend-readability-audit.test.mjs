import assert from 'node:assert/strict';
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import test from 'node:test';
import {
    analyzeSource,
    auditBackendReadability,
    formatReport,
    runCli,
} from './backend-readability-audit.mjs';

async function fixture(t, files) {
    const root = await mkdtemp(join(tmpdir(), 'languon-readability-'));
    t.after(() => rm(root, { recursive: true, force: true }));

    for (const [name, source] of Object.entries(files)) {
        const path = join(root, 'apps/backend/src', name);
        await mkdir(dirname(path), { recursive: true });
        await writeFile(path, source);
    }

    return root;
}

const longBody = Array.from(
    { length: 100 },
    (_, index) => `work(${index});`,
).join('\n');
const longData = `export const values = [\n${'1,\n'.repeat(500)}];\n`;

test('AST measures actual function bodies, methods and callbacks without parsing strings as code', () => {
    const source = `// function fake() {\nconst text = '() => { fake }';
export function choose() {\n${longBody}\n}
const processItem = () => {\n${longBody}\n};
class Store { save() {\n${longBody}\n} }
items.map(() => {\n${longBody}\n});`;
    const result = analyzeSource('runtime.ts', source);

    assert.equal(result.functionCount, 4);
    assert.deepEqual(
        result.longFunctions.map(({ name }) => name),
        ['choose', 'processItem', 'Store.save', 'items.map callback'],
    );

    assert.ok(result.longFunctions.every(({ bodyLines }) => bodyLines === 102));
    assert.deepEqual(result.reasons, ['long-function']);
});

test('reports physical and nonblank lines honestly, including CRLF and no phantom final line', () => {
    const result = analyzeSource(
        'metrics.ts',
        '// comment\r\n\r\nconst text = `x\ny`;\r\n',
    );

    assert.equal(result.physicalLines, 4);
    assert.equal(result.nonblankLines, 3);
    assert.equal(analyzeSource('empty.ts', '').physicalLines, 0);
    assert.equal(analyzeSource('last.ts', 'const x = 1;').physicalLines, 1);
    assert.deepEqual(result.reasons, []);
});

test('names property arrows, accessors, constructors and default exports while ignoring signatures', () => {
    const source = `declare function signature(): void;
class Store {
    constructor() {\n${longBody}\n}
    handler = async () => {\n${longBody}\n};
    get value() {\n${longBody}\n}
}
const options = { run: () => {\n${longBody}\n} };
export default () => {\n${longBody}\n};`;
    const result = analyzeSource('syntax.ts', source);

    assert.equal(result.functionCount, 5);
    assert.deepEqual(
        result.longFunctions.map(({ name }) => name),
        [
            'Store.constructor',
            'handler',
            'Store.value',
            'run',
            'default export',
        ],
    );
});

test('size thresholds are strict and data/config/schema hints stay in the review queue', () => {
    assert.deepEqual(analyzeSource('exact.ts', '\n'.repeat(500)).reasons, []);

    for (const name of [
        'schema.ts',
        'provider-catalog.ts',
        'api-environment.ts',
    ]) {
        const result = analyzeSource(name, longData);

        assert.equal(result.category, 'declarative-review');
        assert.equal(result.functionCount, 0);
        assert.deepEqual(result.reasons, ['large-file']);
    }

    const exactBody = `function exact() {\n${'work();\n'.repeat(98)}}`;
    assert.equal(analyzeSource('exact.ts', exactBody).longFunctions.length, 0);
});

test('inventory excludes non-runtime/generated sources and retains source unchanged', async (t) => {
    const files = {
        'runtime.ts': `export function work() {\n${longBody}\n}`,
        'schema.ts': longData,
        'runtime.test.ts': longData,
        'runtime.spec.ts': longData,
        'types.d.ts': longData,
        'client.generated.ts': longData,
        'generated/client.ts': longData,
        '__generated__/client.ts': longData,
        '__tests__/fixture.ts': longData,
        'fixtures/prices.ts': longData,
        'marked.ts': `// @generated\n${longData}`,
        'also-marked.ts': `/* Code generated by a tool. DO NOT EDIT. */\n${longData}`,
        'ordinary.tsx': 'export const node = <span />;\n',
        'marker-string.ts': "const marker = '@generated';\n",
    };
    const root = await fixture(t, files);
    const result = await auditBackendReadability(root);

    assert.equal(result.scannedFiles, 4);
    assert.equal(result.candidateCount, 2);
    assert.deepEqual(
        result.candidates.map(({ path }) => path),
        ['apps/backend/src/runtime.ts', 'apps/backend/src/schema.ts'],
    );

    assert.equal(
        await readFile(join(root, 'apps/backend/src/runtime.ts'), 'utf8'),
        files['runtime.ts'],
    );
});

test('text is bounded, JSON retains every candidate, and ties have stable path ordering', async (t) => {
    const files = Object.fromEntries(
        Array.from({ length: 23 }, (_, index) => [
            `file-${String(index).padStart(2, '0')}.ts`,
            longData,
        ]),
    );
    const root = await fixture(t, files);
    const result = await auditBackendReadability(root);
    const json = JSON.parse(await runCli(['--json'], root));

    assert.equal(json.candidates.length, 23);
    assert.deepEqual(json, result);
    assert.match(formatReport(result), /Showing 20\/23/);
    assert.doesNotMatch(formatReport(result), /file-20\.ts/);
    assert.equal(json.candidates.at(-1).path, 'apps/backend/src/file-22.ts');
});

test('invalid CLI arguments and malformed sources fail explicitly', async () => {
    for (const args of [['--unknown'], ['--json', '--help'], ['unexpected']]) {
        await assert.rejects(runCli(args), /Usage:/);
    }

    assert.match(await runCli(['--help']), /Read-only advisory/);
    assert.throws(
        () => analyzeSource('broken.ts', 'function broken( {'),
        /Cannot parse broken\.ts/,
    );
});
